"""Generate fdir_params.h from results.json (thresholds + trained isolation model)."""
import json, sys, numpy as np
sys.path.insert(0, "..")
import thruster_sim as ts, fdir as fd

r = json.load(open("../results.json"))
thr, m = r["thresholds"], r["model"]
K, P = fd.kf_steady_gain()
sig = float(np.sqrt(P[0, 0]))
R, kappa0, H = 64, 0.1, 1 / 1000.0
lam = kappa0 + np.arange(R - 1)
inv_var = 1 / (1 + 1 / lam)
half_logvar = 0.5 * np.log(1 + 1 / lam) + 0.5 * np.log(2 * np.pi)


def arr(a, fmt="{:.9e}f"):
    return "{" + ", ".join(fmt.format(x) for x in a) + "}"


L = []
L.append("/* AUTO-GENERATED by gen_params.py - do not edit */")
L.append("#ifndef FDIR_PARAMS_H\n#define FDIR_PARAMS_H\n#include <stdint.h>")
for name, val in [("IB_SET", ts.IB_SET), ("MDOT_SET", ts.MDOT_SET), ("MA_TO_UGS", ts.MA_TO_UGS),
                  ("EPS_INF", ts.EPS_INF), ("C0M", ts.C0 * 1.03), ("CHI0", ts.CHI0),
                  ("ETA0", ts.IB_SET * ts.MA_TO_UGS / ts.MDOT_SET), ("VN0", ts.VN0),
                  ("A_T", 0.0036), ("B_T", 0.0018), ("C_T", 0.045)]:
    L.append(f"#define {name} ({val:.9e}f)")
L.append(f"#define CUSUM_K_Q16 ({int(round(0.5 * 65536))})")
L.append(f"#define THR_CUSUM_Q16 ({int(round(thr['CUSUM'] * 65536))})")
L.append(f"#define KF_K0_Q31 ({int(round(K[0] * 2**31))}LL)")
L.append(f"#define KF_K1_Q40 ({int(round(K[1] * 2**40))}LL)")
L.append(f"#define THR_KF_Q24 ({int(round(thr['KF'] * sig * 2**24))})")
L.append(f"#define THR_BOCPD ({thr["BOCPD"]:.9e}f)")
L.append(f"#define THR_ARC ({thr["ARC"]:.9e}f)")
L.append(f"#define ARC_LLR_PER_EVENT ({np.log(10.0):.9e}f)")
L.append(f"#define ARC_DRIFT ({0.001 * 9:.9e}f)")
L.append(f"#define BO_KAPPA0 ({kappa0}f)")
L.append(f"#define BO_LOG_H ({np.log(H):.9e}f)")
L.append(f"#define BO_LOG_1MH ({np.log1p(-H):.9e}f)")
L.append(f"#define BO_HALF_L2PI ({0.5 * np.log(2 * np.pi):.9e}f)")
L.append(f"static const float BO_INV_LAM[{R-1}] = {arr(1 / lam)};")
L.append(f"static const float BO_INV_VAR[{R-1}] = {arr(inv_var)};")
L.append(f"static const float BO_HALF_LOGVAR[{R-1}] = {arr(half_logvar)};")
Wq = np.array(m["Wq"], dtype=int)
L.append(f"#define ISO_NF {Wq.shape[0]}\n#define ISO_NC {Wq.shape[1]}")
L.append("#define ISO_IN_SCALE (16.0f)")
L.append(f"static const float ISO_MU[ISO_NF] = {arr(m['mu'])};")
L.append(f"static const float ISO_INV_SD[ISO_NF] = {arr(1 / np.array(m['sd']))};")
L.append("static const int8_t ISO_WQ[ISO_NF][ISO_NC] = {" +
         ", ".join("{" + ", ".join(str(v) for v in row) + "}" for row in Wq) + "};")
L.append(f"static const int32_t ISO_BQ[ISO_NC] = {arr(m['bq'], '{:d}')};")
L.append("#endif")
open("fdir_params.h", "w").write("\n".join(L) + "\n")
print("written; THR_KF sigma", sig)
